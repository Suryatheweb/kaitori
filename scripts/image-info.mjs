/**
 * Prints filename, width×h, and KB for every image in public/.
 * No dependencies — parses PNG IHDR, JPEG SOF markers, WebP VP8/VP8L/VP8X.
 * Run: node scripts/image-info.mjs
 * Output: table to stdout + public/images/SIZES.md
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOTS = ['public', 'public/images']

function readUInt16BE(buf, off) {
  return (buf[off] << 8) | buf[off + 1]
}

function pngSize(buf) {
  if (buf.length < 24) return null
  if (buf.readUInt32BE(0) !== 0x89504e47) return null
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
}

function jpegSize(buf) {
  let off = 2
  while (off + 9 < buf.length) {
    if (buf[off] !== 0xff) return null
    const marker = buf[off + 1]
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      return { h: readUInt16BE(buf, off + 5), w: readUInt16BE(buf, off + 7) }
    }
    const len = readUInt16BE(buf, off + 2)
    if (len < 2) return null
    off += 2 + len
  }
  return null
}

function webpSize(buf) {
  if (buf.length < 30) return null
  if (buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WEBP') return null
  const fourcc = buf.toString('ascii', 12, 16)
  if (fourcc === 'VP8X') {
    return {
      w: 1 + (buf[24] | (buf[25] << 8) | (buf[26] << 16)),
      h: 1 + (buf[27] | (buf[28] << 8) | (buf[29] << 16)),
    }
  }
  if (fourcc === 'VP8L') {
    const bits = buf.readUInt32LE(21)
    return { w: (bits & 0x3fff) + 1, h: ((bits >> 14) & 0x3fff) + 1 }
  }
  if (fourcc === 'VP8 ') {
    return { w: (buf[26] | (buf[27] << 8)) & 0x3fff, h: (buf[28] | (buf[29] << 8)) & 0x3fff }
  }
  return null
}

function imageSize(path) {
  const buf = readFileSync(path)
  return pngSize(buf) || webpSize(buf) || jpegSize(buf)
}

function walk(dir) {
  const out = []
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) out.push(...walk(p))
    else if (/\.(png|jpe?g|webp|svg|gif|avif)$/i.test(name)) out.push(p)
  }
  return out
}

const seen = new Set()
const rows = []
for (const root of ROOTS) {
  let files = []
  try {
    files = walk(root)
  } catch {
    continue
  }
  for (const f of files) {
    const abs = f
    if (seen.has(abs)) continue
    seen.add(abs)
    const size = statSync(abs).size
    const dims = imageSize(abs)
    rows.push({
      file: relative(process.cwd(), abs).replaceAll('\\', '/'),
      w: dims?.w ?? '?',
      h: dims?.h ?? '?',
      kb: (size / 1024).toFixed(1),
    })
  }
}

rows.sort((a, b) => a.file.localeCompare(b.file))

const pad = (s, n) => String(s).padEnd(n)
const header = `| ${pad('file', 44)} | ${pad('size (px)', 13)} | ${pad('KB', 8)} |`
const sep = `|${'-'.repeat(46)}|${'-'.repeat(15)}|${'-'.repeat(10)}|`
const lines = rows.map(
  (r) => `| ${pad(r.file, 44)} | ${pad(`${r.w} × ${r.h}`, 13)} | ${pad(r.kb, 8)} |`,
)

console.log(header)
console.log(sep)
for (const l of lines) console.log(l)

const md = [
  '# Image sizes (generated by scripts/image-info.mjs)',
  '',
  'Replace a file with your own image of the **same width × height** to avoid layout shifts.',
  'Regenerate this table with: `node scripts/image-info.mjs`',
  '',
  header,
  sep,
  ...lines,
  '',
].join('\n')

writeFileSync(join('public', 'images', 'SIZES.md'), md)
console.log(`\nWrote public/images/SIZES.md (${rows.length} images)`)
